package build

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"

	"github.com/jespino/go-in-go/gig"
)

// Bindgen returns Go source for package pkg with typed host-side bindings
// for a module: a Module type with a method per export, an Imports
// interface the host implements, and Load/LoadBytes. Signatures are checked
// against the module at load time.
func Bindgen(m *gig.Manifest, pkg, source string) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go-in-go bindgen from %s. DO NOT EDIT.\n\n", source)
	fmt.Fprintf(&b, "// Package %s holds the host bindings of the go-in-go module %s.\npackage %s\n\n", pkg, m.Module, pkg)
	b.WriteString("import (\n\t\"math\"\n\t\"os\"\n\n\t\"github.com/jespino/go-in-go/gig\"\n)\n\n")
	b.WriteString("var _ = math.Float64bits\n\n")

	hasImports := len(m.Imports) > 0
	if hasImports {
		b.WriteString("// Imports are the host functions the module calls.\ntype Imports interface {\n")
		for _, f := range m.Imports {
			writeDoc(&b, f.Doc, "\t")
			fmt.Fprintf(&b, "\t%s(%s) (%s)\n", f.Name, paramList(f.Params), resultList(f.Results))
		}
		b.WriteString("}\n\n")
	}

	fmt.Fprintf(&b, "// Module is a loaded instance of %s.\ntype Module struct {\n\tInstance *gig.Instance\n\tidx [%d]int\n}\n\n", m.Module, max(len(m.Exports), 1))

	impParam, impArg := "", ""
	if hasImports {
		impParam, impArg = ", imports Imports", ", imports"
	}
	fmt.Fprintf(&b, "// Load loads the module file at path.\nfunc Load(path string%s, opts *gig.Options) (*Module, error) {\n", impParam)
	fmt.Fprintf(&b, "\tdata, err := os.ReadFile(path)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n\treturn LoadBytes(data%s, opts)\n}\n\n", impArg)
	fmt.Fprintf(&b, "// LoadBytes loads the module from the contents of its file (e.g. //go:embed).\nfunc LoadBytes(data []byte%s, opts *gig.Options) (*Module, error) {\n", impParam)
	b.WriteString("\tvar o gig.Options\n\tif opts != nil {\n\t\to = *opts\n\t}\n")
	if hasImports {
		b.WriteString("\to.Imports = map[string]gig.Import{\n")
		for _, f := range m.Imports {
			fmt.Fprintf(&b, "\t\t%q: {Sig: %q, Fn: func(c *gig.HostCall) {\n", f.Name, f.Signature())
			var args, rets []string
			slot := 0
			for _, p := range f.Params {
				args = append(args, hostDecode(p.Type, "c.Arg", "c.String", "c.Bytes", slot))
				slot += gig.Slots(p.Type)
			}
			for i := range f.Results {
				rets = append(rets, fmt.Sprintf("r%d", i))
			}
			b.WriteString("\t\t\t")
			if len(rets) > 0 {
				b.WriteString(strings.Join(rets, ", ") + " := ")
			}
			fmt.Fprintf(&b, "imports.%s(%s)\n", f.Name, strings.Join(args, ", "))
			slot = 0
			for i, r := range f.Results {
				b.WriteString("\t\t\t" + hostEncode(r.Type, "c", slot, rets[i]) + "\n")
				slot += gig.Slots(r.Type)
			}
			b.WriteString("\t\t}},\n")
		}
		b.WriteString("\t}\n")
	}
	b.WriteString("\tin, err := gig.LoadBytes(data, &o)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n\tm := &Module{Instance: in}\n")
	for i, f := range m.Exports {
		fmt.Fprintf(&b, "\tif m.idx[%d], err = in.Export(%q, %q); err != nil {\n\t\tin.Close()\n\t\treturn nil, err\n\t}\n", i, f.Name, f.Signature())
	}
	b.WriteString("\treturn m, nil\n}\n\n")
	b.WriteString("// Close unloads the module.\nfunc (m *Module) Close() error { return m.Instance.Close() }\n\n")
	b.WriteString("// GigInstance returns the underlying instance (for gig.Pool).\nfunc (m *Module) GigInstance() *gig.Instance { return m.Instance }\n\n")

	for i, f := range m.Exports {
		writeDoc(&b, f.Doc, "")
		// Results: the export's, plus an error for failures of the call
		// itself, merged into the export's own error result if it has one.
		results := append([]gig.Param(nil), f.Results...)
		ownErr := len(results) > 0 && results[len(results)-1].Type == "error"
		if !ownErr {
			results = append(results, gig.Param{Type: "error"})
		}
		var zeros []string
		for _, r := range results[:len(results)-1] {
			zeros = append(zeros, zero(r.Type))
		}
		fail := "return " + strings.Join(append(zeros, "err"), ", ")
		fmt.Fprintf(&b, "func (m *Module) %s(%s) (%s) {\n", f.Name, paramList(f.Params), resultList(results))
		fmt.Fprintf(&b, "\tf, err := m.Instance.Begin(m.idx[%d])\n\tif err != nil {\n\t\t%s\n\t}\n\tdefer f.End()\n", i, fail)
		slot := 0
		for j, p := range f.Params {
			b.WriteString("\t" + hostSetArg(p.Type, slot, paramName(p, j)) + "\n")
			slot += gig.Slots(p.Type)
		}
		fmt.Fprintf(&b, "\tif err := f.Run(); err != nil {\n\t\t%s\n\t}\n", fail)
		var outs []string
		slot = 0
		for j, r := range f.Results {
			v := fmt.Sprintf("r%d", j)
			switch r.Type {
			case "string", "[]byte", "error":
				method := map[string]string{"string": "RetString", "[]byte": "RetBytes", "error": "RetError"}[r.Type]
				fmt.Fprintf(&b, "\t%s, err := f.%s(%d)\n\tif err != nil {\n\t\t%s\n\t}\n", v, method, slot, fail)
			default:
				fmt.Fprintf(&b, "\t%s := %s\n", v, hostDecode(r.Type, "f.Ret", "", "", slot))
			}
			outs = append(outs, v)
			slot += gig.Slots(r.Type)
		}
		if !ownErr {
			outs = append(outs, "nil")
		}
		b.WriteString("\treturn " + strings.Join(outs, ", ") + "\n}\n\n")
	}

	out, err := format.Source(b.Bytes())
	if err != nil {
		return b.Bytes(), fmt.Errorf("formatting bindings: %w", err)
	}
	return out, nil
}

func writeDoc(b *bytes.Buffer, doc, indent string) {
	for _, line := range strings.Split(doc, "\n") {
		if line == "" || line == exportPragma || line == importPragma {
			continue
		}
		b.WriteString(indent + "// " + line + "\n")
	}
}

func paramName(p gig.Param, i int) string {
	if p.Name == "" {
		return fmt.Sprintf("p%d", i)
	}
	return p.Name
}

func paramList(ps []gig.Param) string {
	var out []string
	for i, p := range ps {
		out = append(out, paramName(p, i)+" "+p.Type)
	}
	return strings.Join(out, ", ")
}

func resultList(ps []gig.Param) string {
	var out []string
	for _, p := range ps {
		out = append(out, p.Type)
	}
	return strings.Join(out, ", ")
}

func zero(t string) string {
	switch t {
	case "string":
		return `""`
	case "[]byte", "error":
		return "nil"
	case "bool":
		return "false"
	}
	return "0"
}

// hostDecode converts slot(s) read through the given accessors to type t.
func hostDecode(t, slot, str, bytes string, i int) string {
	a := fmt.Sprintf("%s(%d)", slot, i)
	switch t {
	case "string":
		return fmt.Sprintf("%s(%d)", str, i)
	case "[]byte":
		return fmt.Sprintf("%s(%d)", bytes, i)
	case "bool":
		return a + " != 0"
	case "float64":
		return "math.Float64frombits(" + a + ")"
	case "float32":
		return "math.Float32frombits(uint32(" + a + "))"
	}
	return fmt.Sprintf("%s(%s)", t, a)
}

func slotValue(t, v string) string {
	switch t {
	case "bool":
		return "boolSlot(" + v + ")"
	case "float64":
		return "math.Float64bits(" + v + ")"
	case "float32":
		return "uint64(math.Float32bits(" + v + "))"
	case "int", "int8", "int16", "int32", "int64":
		return "uint64(int64(" + v + "))"
	}
	return "uint64(" + v + ")"
}

func hostEncode(t, c string, i int, v string) string {
	switch t {
	case "string":
		return fmt.Sprintf("%s.SetString(%d, %s)", c, i, v)
	case "[]byte":
		return fmt.Sprintf("%s.SetBytes(%d, %s)", c, i, v)
	case "error":
		return fmt.Sprintf("%s.SetError(%d, %s)", c, i, v)
	}
	return fmt.Sprintf("%s.SetRet(%d, %s)", c, i, strings.Replace(slotValue(t, v), "boolSlot(", "gig.BoolSlot(", 1))
}

func hostSetArg(t string, i int, v string) string {
	switch t {
	case "string":
		return fmt.Sprintf("f.SetString(%d, %s)", i, v)
	case "[]byte":
		return fmt.Sprintf("f.SetBytes(%d, %s)", i, v)
	}
	return fmt.Sprintf("f.Set(%d, %s)", i, strings.Replace(slotValue(t, v), "boolSlot(", "gig.BoolSlot(", 1))
}
