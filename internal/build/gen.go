package build

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"

	"github.com/jespino/go-in-go/gig"
)

// genModule returns the generated Go file added to the module's main
// package: a C-ABI entry point per export and a body per import.
//
// An export runs on a (reused) goroutine, with the scheduler running on the
// module's system stack until it finishes, so it can block (channels,
// mutexes, time.Sleep). Arguments are copied out of host memory before
// anything else runs.
func genModule(res *scanResult) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by go-in-go. DO NOT EDIT.\n\npackage main\n\n")
	b.WriteString("import (\n\t\"math\"\n\t\"unsafe\"\n)\n\n")
	b.WriteString(moduleHelpers)
	if !res.hasMain {
		b.WriteString("func main() {}\n\n")
	}

	for _, f := range res.exports {
		na, nr := max(f.ArgSlots(), 1), max(f.RetSlots(), 1)
		fmt.Fprintf(&b, "//export gig_export_%s\n", f.Name)
		fmt.Fprintf(&b, "func __gig_export_%s(__args *[%d]uint64, __rets *[%d]uint64) {\n", f.Name, na, nr)
		slot := 0
		var params []string
		for i, p := range f.Params {
			v := fmt.Sprintf("__p%d", i)
			fmt.Fprintf(&b, "\t%s := %s\n", v, decode(p.Type, "__args", slot))
			params = append(params, v)
			slot += gig.Slots(p.Type)
		}
		var results []string
		for i, r := range f.Results {
			v := fmt.Sprintf("__r%d", i)
			fmt.Fprintf(&b, "\tvar %s %s\n", v, r.Type)
			results = append(results, v)
		}
		b.WriteString("\t__gig_exec(func() {\n\t\t")
		if len(results) > 0 {
			b.WriteString(strings.Join(results, ", ") + " = ")
		}
		fmt.Fprintf(&b, "%s(%s)\n\t})\n", f.Name, strings.Join(params, ", "))
		slot = 0
		for i, r := range f.Results {
			b.WriteString(encode(r.Type, "__rets", slot, results[i]))
			slot += gig.Slots(r.Type)
		}
		b.WriteString("}\n\n")
	}

	for idx, f := range res.imports {
		na, nr := max(f.ArgSlots(), 1), max(f.RetSlots(), 1)
		if f.Doc != "" {
			for _, line := range strings.Split(f.Doc, "\n") {
				if strings.TrimSpace(line) == importPragma {
					continue
				}
				b.WriteString("// " + line + "\n")
			}
		}
		var params, results []string
		for i, p := range f.Params {
			params = append(params, fmt.Sprintf("__p%d %s", i, p.Type))
		}
		for _, r := range f.Results {
			results = append(results, r.Type)
		}
		fmt.Fprintf(&b, "func %s(%s) (%s) {\n", f.Name, strings.Join(params, ", "), strings.Join(results, ", "))
		fmt.Fprintf(&b, "\tvar __args [%d]uint64\n\tvar __rets [%d]uint64\n", na, nr)
		slot := 0
		for i, p := range f.Params {
			b.WriteString(encode(p.Type, "__args", slot, fmt.Sprintf("__p%d", i)))
			slot += gig.Slots(p.Type)
		}
		fmt.Fprintf(&b, "\t__gig_hostcall(%d, &__args[0], &__rets[0])\n", idx)
		if len(f.Results) > 0 {
			var rs []string
			slot = 0
			for _, r := range f.Results {
				rs = append(rs, decode(r.Type, "__rets", slot))
				slot += gig.Slots(r.Type)
			}
			b.WriteString("\treturn " + strings.Join(rs, ", ") + "\n")
		}
		b.WriteString("}\n\n")
	}
	out, err := format.Source(b.Bytes())
	if err != nil {
		return b.Bytes(), fmt.Errorf("formatting generated module code: %w", err)
	}
	return out, nil
}

// decode returns an expression converting slots arr[slot...] to type t,
// copying strings and byte slices into the module heap.
func decode(t, arr string, slot int) string {
	a := fmt.Sprintf("%s[%d]", arr, slot)
	switch t {
	case "string":
		return fmt.Sprintf("__gig_string(%s, %s[%d])", a, arr, slot+1)
	case "[]byte":
		return fmt.Sprintf("__gig_bytes(%s, %s[%d])", a, arr, slot+1)
	case "error":
		return fmt.Sprintf("__gig_error(%s, %s[%d])", a, arr, slot+1)
	case "bool":
		return a + " != 0"
	case "float64":
		return "math.Float64frombits(" + a + ")"
	case "float32":
		return "math.Float32frombits(uint32(" + a + "))"
	}
	return fmt.Sprintf("%s(%s)", t, a)
}

// encode returns statements storing v of type t in slots arr[slot...].
func encode(t, arr string, slot int, v string) string {
	switch t {
	case "string":
		return fmt.Sprintf("\t%s[%d], %s[%d] = __gig_from_string(%s)\n", arr, slot, arr, slot+1, v)
	case "[]byte":
		return fmt.Sprintf("\t%s[%d], %s[%d] = __gig_from_bytes(%s)\n", arr, slot, arr, slot+1, v)
	case "error":
		return fmt.Sprintf("\t%s[%d], %s[%d] = __gig_from_error(%s)\n", arr, slot, arr, slot+1, v)
	case "bool":
		return fmt.Sprintf("\t%s[%d] = __gig_from_bool(%s)\n", arr, slot, v)
	case "float64":
		return fmt.Sprintf("\t%s[%d] = math.Float64bits(%s)\n", arr, slot, v)
	case "float32":
		return fmt.Sprintf("\t%s[%d] = uint64(math.Float32bits(%s))\n", arr, slot, v)
	case "int", "int8", "int16", "int32", "int64":
		return fmt.Sprintf("\t%s[%d] = uint64(int64(%s))\n", arr, slot, v)
	}
	return fmt.Sprintf("\t%s[%d] = uint64(%s)\n", arr, slot, v)
}

const moduleHelpers = `var _ = math.Float64bits

//go:linkname __gig_exec runtime.gigExec
func __gig_exec(fn func())

//go:linkname __gig_hostcall runtime.gigHostCall
func __gig_hostcall(index uintptr, args *uint64, rets *uint64)

func __gig_string(p, n uint64) string {
	if n == 0 {
		return ""
	}
	return string(unsafe.Slice((*byte)(unsafe.Pointer(uintptr(p))), n))
}

func __gig_bytes(p, n uint64) []byte {
	if n == 0 {
		return nil
	}
	b := make([]byte, n)
	copy(b, unsafe.Slice((*byte)(unsafe.Pointer(uintptr(p))), n))
	return b
}

type __gig_errorString string

func (e __gig_errorString) Error() string { return string(e) }

func __gig_error(p, n uint64) error {
	if n == 0 {
		return nil
	}
	return __gig_errorString(__gig_string(p, n-1))
}

func __gig_from_string(s string) (uint64, uint64) {
	return uint64(uintptr(unsafe.Pointer(unsafe.StringData(s)))), uint64(len(s))
}

func __gig_from_bytes(b []byte) (uint64, uint64) {
	return uint64(uintptr(unsafe.Pointer(unsafe.SliceData(b)))), uint64(len(b))
}

func __gig_from_bool(b bool) uint64 {
	if b {
		return 1
	}
	return 0
}

func __gig_from_error(err error) (uint64, uint64) {
	if err == nil {
		return 0, 0
	}
	p, n := __gig_from_string(err.Error())
	return p, n + 1
}

`
